// One-time port: copies the email HTML out of the old draft_order.php into src/email-template-html.js.
// The HTML is copied as-is apart from two listed fixes (see applyFix calls). PHP string escaping (\') is
// undone, and each PHP concatenation (' . $var . ') becomes a {{placeholder}}. Fails loudly if anything is left unconverted.
//
// Run: node scripts/port-email-template.js [path/to/draft_order.php]
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const phpFilePath = resolve(process.argv[2] ?? '../draft_orders/draft_order.php');
const outputFilePath = resolve('src/email-template-html.js');
const phpSource = readFileSync(phpFilePath, 'utf8');

const ESCAPED_QUOTE_SENTINEL = '\u0000ESCAPED_QUOTE\u0000';

/** Returns the PHP single-quoted string content between startMarker and endMarker, plus closingTag. */
function extractPhpString(startMarker, endMarker, closingTag) {
  const startIndex = phpSource.indexOf(startMarker);
  if (startIndex === -1) throw new Error(`Start marker not found: ${startMarker}`);

  const contentStartIndex = startIndex + startMarker.length;
  const endIndex = phpSource.indexOf(endMarker, contentStartIndex);
  if (endIndex === -1) throw new Error(`End marker not found: ${endMarker}`);

  return phpSource.slice(contentStartIndex, endIndex) + closingTag;
}

function escapeRegExp(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function convertPhpString(phpString, placeholderMappings, templateName) {
  let convertedString = phpString.replaceAll("\\'", ESCAPED_QUOTE_SENTINEL);

  for (const [phpExpression, placeholderName] of placeholderMappings) {
    const concatenationPattern = new RegExp(`'\\s*\\.\\s*${escapeRegExp(phpExpression)}\\s*\\.\\s*'`, 'g');
    const matchCount = convertedString.match(concatenationPattern)?.length ?? 0;
    if (matchCount === 0) throw new Error(`${templateName}: no match for ${phpExpression}`);
    convertedString = convertedString.replace(concatenationPattern, `{{${placeholderName}}}`);
    console.log(`${templateName}: ${phpExpression} → {{${placeholderName}}} (${matchCount}x)`);
  }

  // Every literal quote in a PHP single-quoted string is escaped, so a bare ' means an unconverted concatenation.
  if (convertedString.includes("'")) {
    throw new Error(`${templateName}: unconverted PHP concatenation remains`);
  }
  return convertedString.replaceAll(ESCAPED_QUOTE_SENTINEL, "'");
}

function toTemplateLiteral(text) {
  const escapedText = text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
  return `\`${escapedText}\``;
}

/** Applies one intentional fix to the template; fails unless the target text occurs exactly once. */
function applyFix(templateText, fixDescription, originalText, fixedText) {
  const occurrenceCount = templateText.split(originalText).length - 1;
  if (occurrenceCount !== 1) {
    throw new Error(`Fix "${fixDescription}": expected 1 match, found ${occurrenceCount}`);
  }
  console.log(`Fix applied: ${fixDescription}`);
  return templateText.replace(originalText, fixedText);
}

const convertedEmailBodyTemplate = convertPhpString(
  extractPhpString("$body = '", "</html>';", '</html>'),
  [
    ['$draft_name', 'draft_name'],
    ['$itg_fname', 'first_name'],
    ['$created_at_formatted', 'created_at'],
    ['$product_list', 'product_list'],
    ['number_format($subtotal_price, 2)', 'subtotal_price'],
    ['$year', 'year'],
  ],
  'EMAIL_BODY_TEMPLATE',
);

// The only intentional changes to the original HTML:
const emailBodyTemplate = applyFix(
  applyFix(
    convertedEmailBodyTemplate,
    'hidden preview text showed "##D123" (draft name already includes #)',
    'Thank you for your order #{{draft_name}}.',
    'Thank you for your order {{draft_name}}.',
  ),
  'unclosed style attribute on the Button section spacer',
  'style="mso-line-height-rule: exactly; bgcolor="#ffffff">&nbsp;',
  'style="mso-line-height-rule: exactly;" bgcolor="#ffffff">&nbsp;',
);

const lineItemRowTemplate = convertPhpString(
  extractPhpString("$product_list .= '", "</tr>';", '</tr>'),
  [
    ['$product_url', 'product_url'],
    ['$product_image_url', 'image_url'],
    ['$product_title', 'title'],
    ['$variants', 'properties'],
    ['number_format(($product_price * $quantity), 2)', 'line_total'],
    ['number_format($product_price, 2)', 'unit_price'],
    ['$quantity', 'quantity'],
  ],
  'LINE_ITEM_ROW_TEMPLATE',
);

const propertyLineTemplate = convertPhpString(
  extractPhpString("$variants .= '", "</span>';", '</span>'),
  [
    ["$valueP['name']", 'name'],
    ["$valueP['value']", 'value'],
  ],
  'PROPERTY_LINE_TEMPLATE',
);

const outputSource = `// GENERATED by scripts/port-email-template.js from the old draft_order.php — do not edit by hand.
// HTML matches the PHP version (except two small fixes listed in the script); PHP variables are {{placeholders}}.

export const PROPERTY_LINE_TEMPLATE = ${toTemplateLiteral(propertyLineTemplate)};

export const LINE_ITEM_ROW_TEMPLATE = ${toTemplateLiteral(lineItemRowTemplate)};

export const EMAIL_BODY_TEMPLATE = ${toTemplateLiteral(emailBodyTemplate)};
`;

writeFileSync(outputFilePath, outputSource);
console.log(`Wrote ${outputFilePath}`);
